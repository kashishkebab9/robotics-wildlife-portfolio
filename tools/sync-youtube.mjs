#!/usr/bin/env node
// Writes data/videos.js with the newest long-form uploads from the YouTube channel.
//
//   node tools/sync-youtube.mjs            (run from anywhere; paths are relative to this file)
//
// Source: the channel's "Videos" tab, which YouTube keeps separate from Shorts. Each id is also
// checked against /shorts/<id> (a regular video redirects to /watch, a Short doesn't). If the page
// can't be fetched or parsed, the existing data/videos.js is left untouched.
// FlockBog's dev server runs this on startup and every few hours (server/portfolio-plugin.js).

import fs from 'fs'
import path from 'path'

const CHANNEL = 'https://www.youtube.com/@gibbons_n_gargoyles'
const LIMIT = 2
const OUT = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'data', 'videos.js')
const HEADERS = {
  'User-Agent': 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/128.0 Safari/537.36',
  'Accept-Language': 'en-US,en;q=0.9',
}

async function get(url, opts = {}) {
  const res = await fetch(url, { headers: HEADERS, signal: AbortSignal.timeout(20000), ...opts })
  return res
}

function initialData(html) {
  const m = html.match(/var ytInitialData = (\{.*?\});<\/script>/s)
  if (!m) throw new Error('ytInitialData not found')
  return JSON.parse(m[1])
}

// Uploads on the Videos tab, newest first: [{ id, title }]
function listUploads(data) {
  const out = []
  const seen = new Set()
  const walk = o => {
    if (Array.isArray(o)) return o.forEach(walk)
    if (!o || typeof o !== 'object') return
    const lock = o.lockupViewModel
    if (lock?.contentId && lock.contentType === 'LOCKUP_CONTENT_TYPE_VIDEO' && !seen.has(lock.contentId)) {
      seen.add(lock.contentId)
      out.push({ id: lock.contentId, title: lock.metadata?.lockupMetadataViewModel?.title?.content || '' })
    }
    const vr = o.videoRenderer // older layout
    if (vr?.videoId && !seen.has(vr.videoId)) {
      seen.add(vr.videoId)
      out.push({ id: vr.videoId, title: (vr.title?.runs || []).map(r => r.text).join('') })
    }
    Object.values(o).forEach(walk)
  }
  walk(data)
  return out
}

async function isShort(id) {
  const res = await get(`https://www.youtube.com/shorts/${id}`, { redirect: 'manual' })
  return res.status === 200 // regular videos answer with a 30x redirect to /watch
}

async function uploadDate(id) {
  try {
    const html = await (await get(`https://www.youtube.com/watch?v=${id}`)).text()
    return html.match(/"uploadDate":"([^"]+)"/)?.[1] || html.match(/itemprop="uploadDate" content="([^"]+)"/)?.[1] || ''
  } catch {
    return ''
  }
}

async function main() {
  const res = await get(`${CHANNEL}/videos`)
  if (!res.ok) throw new Error(`channel page HTTP ${res.status}`)
  const uploads = listUploads(initialData(await res.text()))
  if (!uploads.length) throw new Error('no uploads found on the Videos tab')

  const videos = []
  for (const v of uploads) {
    if (videos.length >= LIMIT) break
    if (await isShort(v.id)) continue
    videos.push({ ...v, published: (await uploadDate(v.id)).slice(0, 10) })
  }

  const js = `// Newest long-form YouTube uploads. Generated by tools/sync-youtube.mjs. Do not edit by hand.\n`
    + `window.WILD_VIDEOS = ${JSON.stringify(videos, null, 1)};\n`
  const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf-8') : ''
  if (prev !== js) fs.writeFileSync(OUT, js)
  console.log(`[youtube] ${videos.length} video(s): ${videos.map(v => v.title).join(' | ')}${prev === js ? ' (unchanged)' : ''}`)
}

main().catch(err => {
  console.error('[youtube] sync skipped:', err.message)
  process.exitCode = 1
})
